export function groupedVocabulary(unit, part) {
  const words = unit.vocabulary.filter(word => word.part === part);
  const byText = new Map(words.map(word => [word.ko, word]));
  return vocabularyGroups[unit.unitId][part].map(([title, text]) => ({
    title,
    words: text.split('|').map(value => byText.get(value))
  }));
}
