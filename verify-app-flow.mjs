import fs from 'node:fs';
import assert from 'node:assert/strict';
import { dialogueJa } from './dialogue-ja.js';
import { unitTranslation } from './content-translations.js';

const storage=new Map();
const listeners={};
const app={innerHTML:'',addEventListener(name,callback){listeners[name]=callback;},insertAdjacentHTML(_position,html){this.innerHTML+=html;}};
globalThis.localStorage={getItem:key=>storage.get(key)||null,setItem:(key,value)=>storage.set(key,String(value))};
globalThis.document={querySelector:selector=>selector==='#app'?app:null};
globalThis.window={scrollTo(){},speechSynthesis:{cancel(){},speak(){}}};
globalThis.location={hash:''};
globalThis.fetch=async url=>({json:async()=>JSON.parse(fs.readFileSync(`.${url}`,'utf8'))});

await import('./app.js');
await new Promise(resolve=>setTimeout(resolve,30));
assert.match(app.innerHTML,/첫 수업 시작하기/);
const click=async(action,extra={})=>{await listeners.click({target:{closest:()=>({dataset:{action,...extra}})}});await new Promise(resolve=>setTimeout(resolve,0));};
await click('start');
const firstDialogue=JSON.parse(fs.readFileSync('content/units/u01.json','utf8')).dialogue.lines;
const completeAudioText=firstDialogue.map(line=>line.text).join(' ');
assert.ok(app.innerHTML.includes(`data-text="${completeAudioText}"`), 'Scene plays all four dialogue lines');
assert.match(app.innerHTML,/대화 1/);
assert.match(app.innerHTML,/alt="하나 얼굴"/);
assert.match(app.innerHTML,/alt="다니엘 얼굴"/);
listeners.change({target:{matches:selector=>selector==='.language-picker',value:'ja'}});
for (const language of ['zh','vi','ne','th','uz','mn']) {
  listeners.change({target:{matches:selector=>selector==='.language-picker',value:language}});
  assert.ok(app.innerHTML.includes(unitTranslation('u01',language,'d1',0)), `${language} dialogue displayed`);
}
listeners.change({target:{matches:selector=>selector==='.language-picker',value:'ja'}});
assert.match(app.innerHTML,/お久しぶりです！/);
assert.doesNotMatch(app.innerHTML,/Long time no see!/);
await click('journey-next');
listeners.change({target:{matches:selector=>selector==='.language-picker',value:'zh'}});
assert.ok(app.innerHTML.includes(unitTranslation('u01','zh','v',0)), 'Chinese vocabulary displayed');
assert.ok(app.innerHTML.includes('vocabulary-group'), 'Vocabulary sections displayed');
assert.ok(app.innerHTML.indexOf('안부를 묻는 표현') < app.innerHTML.indexOf('근황을 답할 때 쓰는 동사'), 'Questions precede answer words');
listeners.change({target:{matches:selector=>selector==='.language-picker',value:'ja'}});
assert.match(app.innerHTML,/그림으로 단어 익히기/);
await click('journey-next');
listeners.change({target:{matches:selector=>selector==='.language-picker',value:'vi'}});
assert.ok(app.innerHTML.includes(unitTranslation('u01','vi','g',0)), 'Vietnamese grammar example displayed');
listeners.change({target:{matches:selector=>selector==='.language-picker',value:'ja'}});
assert.match(app.innerHTML,/만드는 법/);
await click('journey-next');
assert.match(app.innerHTML,/문장 배열/);
assert.ok(app.innerHTML.includes(`data-text="${completeAudioText}"`), 'Practice plays all four dialogue lines');
assert.match(app.innerHTML,/회사에 다니고 한국어도 배워요/);
await click('journey-choice',{index:'0'});
await click('journey-check');
const unit=JSON.parse(fs.readFileSync('content/units/u01.json','utf8'));
const count=unit.dialoguePractice.one.sentence.trim().split(/\s+/).length;
for(let i=count-1;i>=0;i--)await click('journey-token',{index:String(i)});
await click('journey-puzzle-check');
await click('journey-next');
assert.match(app.innerHTML,/대화 2/);
assert.match(app.innerHTML,/先週は何をしましたか。/);
await click('journey-next');
assert.match(app.innerHTML,/그림으로 단어 익히기/);
await click('journey-next');
assert.match(app.innerHTML,/주의할 점/);
await click('journey-next');
assert.match(app.innerHTML,/대화 2 연습/);
assert.match(app.innerHTML,new RegExp(unit.dialogue2.lines[0].text.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')));
await click('journey-choice',{index:'0'});
await click('journey-check');
const count2=unit.dialoguePractice.two.sentence.trim().split(/\s+/).length;
for(let i=count2-1;i>=0;i--)await click('journey-token',{index:String(i)});
await click('journey-puzzle-check');
await click('journey-next');
assert.match(app.innerHTML,/귀로 먼저 만나 봐요/);
const saved=JSON.parse(storage.get('korean-journey-v1'));
assert.equal(Object.keys(saved.reviews).length,unit.vocabulary.length);
for(let i=1;i<=14;i++){
  const lesson=JSON.parse(fs.readFileSync(`content/units/u${String(i).padStart(2,'0')}.json`,'utf8'));
  assert.equal(dialogueJa[lesson.unitId]?.scene1.length,lesson.dialogue.lines.length,`${lesson.unitId} dialogue 1`);
  assert.equal(dialogueJa[lesson.unitId]?.scene2.length,lesson.dialogue2.lines.length,`${lesson.unitId} dialogue 2`);
}
console.log('Both dialogue practices, detailed grammar, and listening transition: OK');
